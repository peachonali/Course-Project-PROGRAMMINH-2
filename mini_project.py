ax.bar(calories.index, calories , color='tomato')  # กราฟแท่ง (Column Chart)
ax.plot(calories.index, calories, color='black', marker='o')    # กราฟเส้น (Line Chart)

ax.set_xlabel('Workout Type', fontsize=16 )      # กำหนดชื่อแกน X
ax.set_ylabel('Average Calories Burned', fontsize=16, fontweight='bold')   # กำหนดชื่อแกน Y
ax.set_title('Calories Burned by Workout Type', fontsize=16, fontweight='bold')    # กำหนดชื่อหัวข้อกราฟ
plt.show()

